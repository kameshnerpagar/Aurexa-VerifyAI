const express = require('express');
const router = express.Router();
const { db } = require('../db');
const { v4: uuidv4 } = require('uuid');
const { logAuditEvent } = require('../services/auditLogger');

// Generate comprehensive Application Verification Report Data Structure
router.get('/application/:id', (req, res) => {
  try {
    const { id } = req.params;
    const app = db.prepare(`
      SELECT a.*, i.name as institution_name, i.current_pid, i.state, i.district, i.address, i.pin_code,
             i.contact_person, i.email as institution_email, i.phone as institution_phone, i.established_year, i.type as institution_type
      FROM applications a
      JOIN institutions i ON a.institution_id = i.id
      WHERE a.id = ?
    `).get(id);

    if (!app) {
      return res.status(404).json({ success: false, message: 'Application not found' });
    }

    const details = db.prepare('SELECT * FROM application_details WHERE application_id = ?').get(id);
    const docs = db.prepare('SELECT * FROM documents WHERE application_id = ? ORDER BY upload_date ASC').all(id);

    for (const d of docs) {
      d.extractions = db.prepare('SELECT * FROM document_extractions WHERE document_id = ?').all(d.id);
      d.verification_records = db.prepare('SELECT * FROM verification_records WHERE document_id = ?').all(d.id).map(vr => ({
        ...vr,
        details: vr.details_json ? JSON.parse(vr.details_json) : {}
      }));
    }

    const findings = db.prepare('SELECT * FROM cross_document_findings WHERE application_id = ? ORDER BY severity DESC').all(id);
    const evaluations = db.prepare(`
      SELECT e.*, r.rule_code, r.name as rule_name, r.severity as rule_severity, r.aicte_handbook_ref
      FROM compliance_evaluations e
      JOIN compliance_rules r ON e.rule_id = r.id
      WHERE e.application_id = ?
      ORDER BY r.rule_code ASC
    `).all(id);

    const infrastructure = db.prepare('SELECT * FROM infrastructure_evidence WHERE application_id = ?').all(id).map(inf => ({
      ...inf,
      detected_elements: inf.detected_elements_json ? JSON.parse(inf.detected_elements_json) : []
    }));

    const validationRunId = `VR-REP-${uuidv4().slice(0, 8).toUpperCase()}`;
    const generatedAt = new Date().toISOString();

    logAuditEvent({
      actor_name: 'AICTE Official Portal',
      actor_role: 'system',
      application_id: id,
      action: 'REPORT_GENERATED',
      target_type: 'Report',
      target_ref: validationRunId,
      outcome: 'Success',
      details: { format: 'Official AICTE Decision-Support Verification Report' }
    });

    res.json({
      success: true,
      report: {
        validationRunId,
        generatedAt,
        organization: 'All India Council for Technical Education (AICTE)',
        productName: 'Aurexa VerifyAI',
        tagline: 'Intelligent Verification. Transparent Compliance. Faster Decisions.',
        problemStatement: 'SIH26261: AI-Powered Application Validation & Document Authentication',
        application: app,
        details: {
          ...details,
          programmes: details && details.programmes_json ? JSON.parse(details.programmes_json) : [],
          proposed_intake: details && details.proposed_intake_json ? JSON.parse(details.proposed_intake_json) : {}
        },
        documents: docs,
        findings,
        evaluations,
        infrastructure,
        disclaimer: 'IMPORTANT STATUTORY NOTICE: This report is generated by Aurexa VerifyAI as an automated decision-support dossier. AI classifications, OCR extractions, and heuristic risk scores do not constitute formal statutory approval or final institutional rejection. Authorized AICTE Competent Authorities retain ultimate regulatory jurisdiction.'
      }
    });
  } catch (err) {
    console.error('[Report Generation Error]', err);
    res.status(500).json({ success: false, message: err.message });
  }
});

// CSV Export for Application Summary
router.get('/export/csv', (req, res) => {
  try {
    const apps = db.prepare(`
      SELECT a.id, i.name as institution_name, i.current_pid, a.category, a.academic_year,
             a.overall_status, a.risk_score, a.risk_level, a.missing_doc_count,
             a.discrepancy_count, a.compliance_status, a.submission_date, a.last_updated
      FROM applications a
      JOIN institutions i ON a.institution_id = i.id
      ORDER BY a.last_updated DESC
    `).all();

    const header = 'Application ID,Institution Name,PID,Category,Academic Year,Status,Risk Score,Risk Level,Missing Docs,Discrepancies,Compliance Summary,Submission Date,Last Updated\n';
    const rows = apps.map(a => [
      `"${a.id}"`,
      `"${(a.institution_name || '').replace(/"/g, '""')}"`,
      `"${a.current_pid || ''}"`,
      `"${a.category}"`,
      `"${a.academic_year}"`,
      `"${a.overall_status}"`,
      a.risk_score,
      `"${a.risk_level}"`,
      a.missing_doc_count,
      a.discrepancy_count,
      `"${(a.compliance_status || '').replace(/"/g, '""')}"`,
      `"${a.submission_date || ''}"`,
      `"${a.last_updated || ''}"`
    ].join(',')).join('\n');

    res.setHeader('Content-Type', 'text/csv');
    res.setHeader('Content-Disposition', 'attachment; filename="AICTE_AurexaVerifyAI_Applications.csv"');
    res.send(header + rows);
  } catch (err) {
    res.status(500).json({ success: false, message: err.message });
  }
});

module.exports = router;
